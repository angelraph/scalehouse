// Copies the compiled ScaleTicket ABI out of Foundry's build output into a typed module the
// app imports. Run after `forge build` whenever the contract changes.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const artifact = JSON.parse(
  readFileSync(path.join(here, "../../contracts/out/ScaleTicket.sol/ScaleTicket.json"), "utf8"),
);
const out = `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit by hand.\nexport const scaleTicketAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`;
writeFileSync(path.join(here, "../lib/abi.ts"), out);
console.log(`Wrote ${artifact.abi.length} ABI entries to lib/abi.ts`);
